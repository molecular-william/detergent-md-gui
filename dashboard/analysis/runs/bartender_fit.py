"""BARTENDER's fit of a detergent's bonded terms, as an analysis a run can be asked for.

Optional by design: BARTENDER is not in any run type's stage list, and this is not part of a default pipeline. It is
queued against a completed run whose atomistic reference and mapping already exist, and what it produces is a *check*:
the bonded parameters it fits to that run's own atomistic ensemble, beside the terms the draft generated by other means.

Why it is worth having: 13 of the DDM draft's 25 terms are geometric fallbacks rather than published values -- the
head-tail junction and the ring-type pairs with blanket force constants -- and this is the only thing in the toolchain
that fits those from data.

Two reconciliations it has to make, both learned by doing it by hand first:

  the virtual sites   the exporter's `.ndx` names the *physical* beads while the generated topology's atoms include
                      the ring virtual sites, so the two number the molecule differently. The topology is renumbered
                      to its physical beads and `virtual_sitesn` dropped, because a virtual site has no atoms to fit.
  the trajectory      `-owntraj` takes DCD or multi-PDB, and this GROMACS writes XTC even when asked for `.dcd`, so
                      the trajectory is written here.

What it refuses: a run with no atomistic reference mapped onto the beads, because there is nothing to fit against.
"""
from __future__ import annotations

import json
import os
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

import MDAnalysis as mda
import numpy as np

REPORT = 'bartender-fit.json'
#: A fit reads a trajectory; it does not simulate. Minutes, not hours, and a task that never returns is worse than one
#: that fails.
TOOL_TIMEOUT = 1200
FITTED = 'gmx_out.itp'
TRAJECTORY = 'solute_heavy.dcd'
INPUT_FILE = 'bartender.inp'

SECTIONS = ('bonds', 'constraints', 'angles', 'dihedrals')


def _run(command, cwd, timeout=None, env=None):
    """Run a tool with no terminal to answer: BARTENDER under an analysis subprocess went into `Sl` and stayed there,
    where the same command in a shell finished in a minute -- a prompt with nothing to answer it. `stdin=DEVNULL` turns
    that into an end of input, and the timeout turns it into a failure rather than a task that never returns."""
    return subprocess.run(command, cwd=cwd, capture_output=True, text=True, timeout=timeout or TOOL_TIMEOUT,
                          env=env, stdin=subprocess.DEVNULL, check=True)


def find(root: Path, pattern: str) -> Path | None:
    matches = sorted(Path(root).glob(pattern))
    return matches[0] if matches else None


def physical_topology(topology_text: str, beads: list[dict]) -> tuple[str, list[str]]:
    """The generated topology renumbered to its physical beads, and the names it kept.

    A virtual site has no atoms, so it is not a bead BARTENDER can fit. Dropping it renumbers the molecule, and every
    row that named it goes with it; the ring pairs themselves are physical, so nothing that is fitted is lost.
    """
    virtual = {index for index, bead in enumerate(beads, 1) if bead.get('virtual_site')}
    kept = [index for index in range(1, len(beads) + 1) if index not in virtual]
    renumber = {old: new for new, old in enumerate(kept, 1)}
    out, section = [], None
    for line in topology_text.splitlines():
        body = line.split(';', 1)[0].strip()
        if body.startswith('['):
            section = body.strip('[] ').strip().lower()
            if section != 'virtual_sitesn':
                out.append(line)
            continue
        if section == 'virtual_sitesn':
            continue
        if not body:
            out.append(line)
            continue
        if section == 'atoms':
            index = int(body.split()[0])
            if index in virtual:
                continue
            fields = body.split()
            fields[0] = str(renumber[index])
            fields[5] = str(renumber[index])
            out.append(' '.join(fields))
            continue
        if section == 'exclusions':
            # Every field is an atom number. A row that names a dropped virtual site goes, and a row that does not is
            # renumbered -- an `[ exclusions ]` row naming a bead that no longer exists is not a valid topology.
            fields = line.split()
            indices = [int(field) for field in fields]
            if any(index in virtual for index in indices):
                continue
            out.append(' '.join(str(renumber[index]) for index in indices))
            continue
        width = {'constraints': 2, 'bonds': 2, 'angles': 3, 'dihedrals': 4}.get(section, 0)
        if width:
            fields = line.split()
            head = [int(value) for value in fields[:width]]
            if any(index in virtual for index in head):
                continue
            out.append(' '.join([str(renumber[index]) for index in head] + fields[width:]))
            continue
        out.append(line)
    names = [bead['name'] for index, bead in enumerate(beads, 1) if index in renumber]
    return '\n'.join(out) + '\n', names


def fitted_terms(text: str) -> dict:
    """`gmx_out.itp` as `{section: [rows]}`, accumulating: BARTENDER writes `[ angles ]` twice.

    The second `[ angles ]` holds commented alternatives, so a parser that resets on a repeated header throws the
    fitted angles away -- which is what a first attempt did, and the run then went ahead without them.
    """
    sections, current = {}, None
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith('['):
            current = stripped.strip('[] ').strip('[').strip(']').lower()
            sections.setdefault(current, [])
            continue
        if not stripped or stripped.startswith(';') or current is None:
            continue
        sections[current].append(stripped.split(';')[0].strip())
    return {section: [row for row in sections.get(section, []) if row] for section in SECTIONS}


def model_topology(candidates: list[Path]) -> Path | None:
    """The run's CG model among the ITPs a stage directory holds.

    It holds several: the reference the mapping was fitted against, a coordinate seed, and the model the CG simulation
    was built from. Taking the first by name picked a seed once, and the fit then ran against a different parameter set
    -- visible only by comparing the input it produced with the one that works. The fitted interaction topology is the
    model, so it is preferred and named; whatever is chosen is reported.
    """
    ordered = sorted(candidates, key=lambda path: (0 if path.stem.endswith('_ff_inter') else
                                                   1 if path.stem.endswith('_initial') else 2, path.name))
    return ordered[0] if ordered else None


def ring_lengths(terms: dict) -> dict:
    """The six ring constraint lengths from `[ constraints ]`, as `{'1-2': nm}`."""
    lengths = {}
    for row in terms.get('constraints', []):
        fields = row.split()
        if len(fields) >= 4:
            lengths[f'{fields[0]}-{fields[1]}'] = float(fields[3])
    return lengths


def ensemble_distances(structure: Path, trajectory: Path, beads: list[dict]) -> dict:
    """The AA ensemble's own mean and spread for every ring pair, which is what a fit is checked against.

    A single frame is not a target: comparing a fit to one is what made the same fit look 5% short of a pair it was
    1.4% off.
    """
    universe = mda.Universe(str(structure), str(trajectory))
    heavy = [atom.index for atom in universe.atoms if not atom.name.startswith('H')]
    heavy_to_all = {position: index for position, index in enumerate(heavy, 1)}
    groups = {bead['name']: [heavy_to_all[int(index)] for index in bead.get('atoms') or []]
              for bead in beads if not bead.get('virtual_site')}
    for bead in beads:
        if bead.get('virtual_site'):
            groups[bead['name']] = [index for parent in bead['virtual_site'].get('parents', [])
                                    for index in groups.get(parent, [])]
    names = [bead['name'] for bead in beads if not bead.get('virtual_site')]
    series = [(first, second) for index, first in enumerate(names) for second in names[index + 1:]]
    collected = {pair: [] for pair in series}
    for _ in universe.trajectory:
        centres = {name: universe.atoms[indices].positions.mean(axis=0) / 10.0 for name, indices in groups.items()}
        for pair in series:
            collected[pair].append(float(np.linalg.norm(centres[pair[0]] - centres[pair[1]])))
    return {'-'.join(pair): {'mean_nm': float(np.mean(values)), 'sd_nm': float(np.std(values)), 'frames': len(values)}
            for pair, values in collected.items()}


def bartender_command(bartender, cpus, *, geometry='solute_heavy.gro', trajectory=TRAJECTORY,
                      inputs=INPUT_FILE) -> list[str]:
    """The invocation, in one place so what it asks for is readable and pinned.

    `-refit` fits the bonded parameters from a trajectory rather than from BARTENDER's own sampling, and `-owntraj`
    supplies that trajectory: the run's own atomistic ensemble, which is the reference this project measures against.
    `-noplot` because a headless analysis has nowhere to put a plot.
    """
    return [str(bartender), '-refit', '-owntraj', str(trajectory), '-noplot', '-cpus', str(cpus),
            str(geometry), str(inputs)]


def shell_command(bartender, cpus, region, **kwargs) -> list[str]:
    """The invocation as the tool's own instructions run it: through its environment file.

    BARTENDER's INSTALL says to source `bartender_config.sh`, which sets `XTBHOME`, `OMP_STACKSIZE` and
    `ulimit -s unlimited`. Running the binary directly instead is what made the same fit take minutes under an
    analysis where it takes one in a shell -- the flags were identical, the environment was not.
    """
    inner = ' '.join(shlex.quote(part) for part in bartender_command(bartender, cpus, **kwargs))
    return ['bash', '-c', f'source {shlex.quote(str(Path(region) / "bartender_config.sh"))}; exec {inner}']


def run(work, payload=None) -> dict:
    """Fit the molecule's bonded terms with BARTENDER and report them beside the ensemble they came from."""
    from ...execution import tools

    work = Path(work)
    payload = dict(payload or {})
    bartender = tools.tool_path('bartender')
    if not bartender:
        raise ValueError('BARTENDER is not resolvable: check config/tools.json and that the tool is present')
    region = Path(bartender).parent
    writer = region / 'write_bartender_inp.py'

    model_file = find(work, '**/model.json')
    structure = find(work, '**/1_AA-reference/prod/lig.gro') or find(work, '**/lig.gro')
    trajectory = find(work, '**/1_AA-reference/prod/lig.xtc') or find(work, '**/lig.xtc')
    ndx = find(work, '**/mapping.ndx')
    topology_file = model_topology([path for path in Path(work).glob('**/3_initial_CG/*.itp')
                                    if 'martini' not in path.name.lower()])
    missing = [name for name, value in (('model.json', model_file), ('the atomistic structure', structure),
                                        ('the atomistic trajectory', trajectory), ('the mapping `.ndx`', ndx),
                                        ('the CG topology', topology_file)) if value is None]
    if missing:
        raise ValueError('this run does not carry what a fit needs: ' + ', '.join(missing))
    assert model_file and structure and trajectory and ndx and topology_file  # the check above

    model_path, structure_path, trajectory_path = Path(model_file), Path(structure), Path(trajectory)
    ndx_path, topology_path = Path(ndx), Path(topology_file)
    model = json.loads(model_path.read_text())
    beads = model['beads']

    # The geometry, in the mapping's own heavy-atom numbering: the same order every file here speaks.
    lines = structure_path.read_text().splitlines()
    body = [line for line in lines[2:-1] if not line[10:15].strip().startswith('H')]
    (work / 'solute_heavy.gro').write_text('\n'.join(['the solute, heavy atoms, in the mapping\'s order',
                                                      str(len(body)), *body, lines[-1]]) + '\n')

    universe = mda.Universe(str(structure_path), str(trajectory_path))
    heavy = universe.select_atoms('not name H*')
    with mda.Writer(str(work / TRAJECTORY), len(heavy)) as writer_dcd:
        for _ in universe.trajectory:
            writer_dcd.write(heavy)

    physical, names = physical_topology(topology_path.read_text(), beads)
    (work / 'physical.itp').write_text(physical)

    # The `.ndx` may already sit where the tool expects it; copying a file onto itself is an error, not a no-op.
    if ndx_path.resolve() != (work / 'mapping.ndx').resolve():
        shutil.copy2(ndx_path, work / 'mapping.ndx')
    _run([sys.executable, str(writer), '-n', 'mapping.ndx', '-i', 'physical.itp', '-o', INPUT_FILE], cwd=work)

    environment = dict(os.environ)
    environment['BTROOT'] = str(region)
    cpus = int(payload.get('cpus') or 8)
    _run(shell_command(bartender, cpus, region), cwd=work, env=environment)

    fitted = fitted_terms((work / FITTED).read_text()) if (work / FITTED).is_file() else {}
    ensemble = ensemble_distances(structure_path, trajectory_path, beads)
    physical_names = [bead['name'] for bead in beads if not bead.get('virtual_site')]
    pairs = {}
    for row in fitted.get('constraints', []):
        fields = row.split()
        if len(fields) < 4:
            continue
        first, second = physical_names[int(fields[0]) - 1], physical_names[int(fields[1]) - 1]
        key = '-'.join(sorted((first, second)))
        measured = ensemble.get(key)
        pairs[key] = {'fitted_nm': float(fields[3]),
                      'ensemble_nm': measured['mean_nm'] if measured else None,
                      'ensemble_sd_nm': measured['sd_nm'] if measured else None,
                      'difference_nm': (float(fields[3]) - measured['mean_nm']) if measured else None,
                      'difference_pct': (100.0 * (float(fields[3]) - measured['mean_nm']) / measured['mean_nm']
                                         if measured and measured['mean_nm'] else None)}
    return {
        'molecule_id': model.get('molecule_id') or model.get('name'),
        'topology': topology_path.name,
        'beads_fitted': len(physical_names),
        'terms': {section: len(rows) for section, rows in fitted.items()},
        'ring_constraints': pairs,
        'ensemble': ensemble,
        'fitted_topology': FITTED if (work / FITTED).is_file() else None,
        'target': ('the run\'s own atomistic ensemble, through `-owntraj`: this fit is checked against the same '
                   'reference the project measures against, not against BARTENDER\'s own GFN sampling'),
        'interpretation': ('Each fitted ring length is compared with the ensemble mean of the same pair over the '
                           'trajectory. A fit inside the ensemble\'s own spread says the fit reproduces the geometry '
                           'the molecule has; the force constants beside it are what there is to adopt where the '
                           'draft had a fallback.'),
        'reference': 'BARTENDER, https://github.com/rmera/bartender',
    }

    monkeypatch.setattr(aa, 'gromacs_flavour', lambda *arguments, **keywords: 'mpi')
    run = tmp_path / 'run'
    run.mkdir()
    with paths.use(paths.Paths(project_root=repo, workspace=tmp_path / 'workspace')):
        selected = aa_molecules.selection(repo / 'molecules', 'Fixture', run_type='aa_only')

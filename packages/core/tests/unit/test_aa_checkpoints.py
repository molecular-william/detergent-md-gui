"""The checkpoint cadence setting, the stage declarations it serves, and the generated continue branch.

`mdrun_cpt` is a run setting whose default is the project's ten minutes: every run records it and its mdrun carries
`-cpt 10` unless the caller names another. A bare settings dict still emits no flag (the builder only prints what it
is given), which is why a caller that predates the setting renders the command it always did. Every stage whose mdrun
writes a checkpoint says
so in its `Stage`, and the AA stages generated by `aa.prepare_run` take it when the executor names it in
`MDRUN_CONTINUE` -- appending to the trajectory that already exists instead of running `grompp` again.
"""
import json
import os
import shutil
import subprocess

import pytest
from dashboard import features, paths
from dashboard.execution import environment, forcefields, run_scripts
from dashboard.execution.adapters import aa, cg
from dashboard.execution.environment import ROOT

from detergent_pdc.execution.adapters import pdc
from detergent_validation.execution.adapters import osmotic

from tests.harness import support

#: The stages whose mdrun writes a checkpoint, and the file each writes. A minimisation writes none, which is why it
#: is named as an exception rather than inferred: GROMACS itself is the authority on that, and this table is it.
MDRUN_CHECKPOINTS = {
    'aa': {'AA NVT equilibration': 'run.cpt', 'AA NPT equilibration': 'run.cpt',
           'AA NPT production': 'run.cpt'},
    'cg': {'AA reference': '3-run.cpt', 'CG simulation': 'md.cpt'},
    'pdc': {'NVT equilibration': 'system.cpt', 'NPT equilibration': 'system.cpt',
            'CG assessment MD': 'prod/run.cpt', 'CG extension MD': ('prod/run.cpt', 'run.cpt')},
}
MINIMISATION = {'AA minimization', 'Energy minimisation'}
#: The AA stages are generated rather than script-backed, so the test names the ones that run dynamics.
GENERATED_AA_MDRUN = set(MDRUN_CHECKPOINTS['aa'])


def _runs_mdrun(stage):
    if stage.script is None:
        return stage.name in GENERATED_AA_MDRUN
    return 'mdrun' in run_scripts.code_path(stage.script, root=ROOT).read_text()


def test_the_untouched_command_is_byte_identical_and_the_cadence_only_appears_when_named():
    """A settings dict nobody touched has to render the command every earlier run rendered."""
    untouched = '-ntomp 8 -gpu_id 0 -nb gpu -pin on -pme gpu -pmefft gpu'
    assert aa.mdrun_command_flags({}, 'production', 'mpi') == ('', untouched)
    assert aa.mdrun_command_flags({}, 'em', 'mpi')[1] == '-ntomp 8 -gpu_id 0 -nb gpu -pin on'
    assert aa.mdrun_command_flags({'mdrun_cpt': 20}, 'production', 'mpi')[1] == f'{untouched} -cpt 20'
    assert aa.mdrun_command_flags({'mdrun_cpt': 1}, 'em', 'mpi')[1].endswith(' -cpt 1')


def test_the_cadence_is_a_bounded_integer_setting():
    assert aa.SETTING_SPECS['mdrun_cpt'] == ('Checkpoint interval (minutes)', 1, 100000)
    # The project's cadence, recorded by every run rather than left to GROMACS' own fifteen.
    assert aa.DEFAULTS['mdrun_cpt'] == 10
    assert aa.normalize_settings({})['mdrun_cpt'] == 10
    assert aa.mdrun_command_flags(aa.normalize_settings({}), 'production', 'mpi')[1].endswith(' -cpt 10')
    assert aa.normalize_settings({'mdrun_cpt': '45'})['mdrun_cpt'] == 45
    with pytest.raises(ValueError, match='mdrun_cpt must be an integer'):
        aa.normalize_settings({'mdrun_cpt': 2.5})
    with pytest.raises(ValueError, match='between 1 and 100000'):
        aa.normalize_settings({'mdrun_cpt': 0})


def test_an_aa_cg_run_keeps_the_cadence_for_its_own_stages():
    assert 'mdrun_cpt' in cg.RUN_EXECUTION_SETTINGS
    assert cg.run_settings({'mdrun_cpt': 25, 'aa_nvt_ps': 10}) == {'mdrun_cpt': 25}


def test_every_stage_that_checkpoints_declares_its_file():
    features.ensure()
    tables = {'aa': aa.STAGE_DEFS, 'cg': cg.STAGE_DEFS, 'pdc': pdc.STAGES}
    for name, stages in tables.items():
        assert [stage.name for stage in stages if stage.resumes_in_place] == []
        for stage in stages:
            expected = MDRUN_CHECKPOINTS[name].get(stage.name)
            if _runs_mdrun(stage) and stage.name not in MINIMISATION:
                assert stage.checkpoint == expected, f'{name}: {stage.name} declares {stage.checkpoint!r}'
            else:
                assert stage.checkpoint is None, f'{name}: {stage.name} should declare no checkpoint'
    # The extension can end at one of two legs, so it names both; the first that exists wins.
    assert pdc.stage_by_name('CG extension MD').checkpoint == ('prod/run.cpt', 'run.cpt')


def test_resolve_carries_the_checkpoint_and_the_in_place_flag():
    stage = Stage('x {name}', 'stages/{name}/run.sh', checkpoint='{name}/run.cpt', resumes_in_place=True)
    resolved = stage.resolve({'name': '04_nvt'})
    assert resolved.checkpoint == '04_nvt/run.cpt' and resolved.resumes_in_place is True
    pair = Stage('x', 'x.sh', checkpoint=('a.cpt', 'b.cpt')).resolve()
    assert pair.checkpoint == ('a.cpt', 'b.cpt') and pair.resumes_in_place is False


def test_the_osmotic_series_resumes_in_place_rather_than_naming_a_checkpoint():
    """Its driver loops each condition's unfinished mdrun with `-cpi`; there is no one checkpoint to name."""
    stage = osmotic.STAGE_DEFS[0]
    assert stage.resumes_in_place is True
    assert stage.checkpoint is None
    assert osmotic.STAGES[0][0] == stage.name



def run_stage(run, stage, **env):
    """Run one generated stage script with a stub `gmx`, returning the argument list of every call it made."""
    stage_dir = run / 'stages' / stage
    # The leg before this one writes `system.top`; the stage's first line copies it forward.
    (stage_dir.parent / '04_nvt').mkdir(exist_ok=True)
    (stage_dir.parent / '04_nvt/system.top').write_text('')
    bin_dir = run / 'bin'
    bin_dir.mkdir(exist_ok=True)
    gmx = bin_dir / 'gmx'
    gmx.write_text('#!/bin/bash\nprintf "%s\\n" "$*" >> "$GMX_CALLS"\n')
    gmx.chmod(0o755)
    calls = run / 'calls.txt'
    calls.write_text('')
    child = {**os.environ, 'PATH': f'{bin_dir}:{os.environ["PATH"]}', 'GMX_CALLS': str(calls), **env}
    subprocess.run(['bash', stage_dir / 'run.sh'], cwd=stage_dir, env=child, check=True,
                   capture_output=True, text=True)
    return calls.read_text().splitlines()


def test_the_generated_leg_continues_from_the_named_checkpoint_and_appends(prepared):
    run, settings = prepared
    stage_dir = run / 'stages/05_npt'
    checkpoint = stage_dir.resolve() / 'run.cpt'
    # The failed leg left the checkpoint it would continue from; `-ef` compares the file, not its spelling.
    checkpoint.write_text('')
    _, flags = aa.mdrun_command_flags(settings, 'npt', 'mpi')

    without = run_stage(run, '05_npt')
    assert any('grompp' in call for call in without), without
    assert f'mdrun -deffnm run {flags} -v' in without, without
    assert not any('-cpi' in call or '-append' in call for call in without), without

    continued = run_stage(run, '05_npt', MDRUN_CONTINUE=str(checkpoint))
    assert not any('grompp' in call for call in continued), continued
    assert continued == [f'mdrun -deffnm run -cpi {checkpoint} -append {flags} -v'], continued


def test_a_checkpoint_naming_another_stage_leaves_the_script_on_its_usual_path(prepared):
    """Only this stage's own final checkpoint continues it; anything else is a fresh leg."""
    run, _ = prepared
    calls = run_stage(run, '05_npt', MDRUN_CONTINUE=str(run / 'stages/04_nvt/run.cpt'))
    assert any('grompp' in call for call in calls), calls
    assert not any('-cpi' in call for call in calls), calls

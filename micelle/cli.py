import argparse,json,sys,re
from pathlib import Path
import numpy as np
from .registry import load_template,validate_template
from .packing import golden_angle_directions
from .repack import repack
from .geometry import box_for
from .solvation import add_solvent
from .output import write_gro,write_manifest
from .validation import validate_positions,write_report
from .orientation import infer_orientation
from .gromacs import grompp

def pdb_positions(path):
 out=[]
 for line in Path(path).read_text().splitlines():
  if line.startswith(('ATOM  ','HETATM')):
   try: out.append([float(line[30:38])/10,float(line[38:46])/10,float(line[46:54])/10])
   except ValueError: pass
 return np.asarray(out,float)
def build(a):
 t=load_template(a.template); issues=validate_template(t)
 protein=pdb_positions(a.protein) if a.protein else np.empty((0,3)); dirs=golden_angle_directions(max(a.aggregation_number*4,32),a.seed)
 centers,packing=repack(None,dirs,protein, a.radius,a.aggregation_number,a.seed)
 report=validate_positions(centers,a.aggregation_number); orientation=infer_orientation(protein) if len(protein) else infer_orientation([])
 report.update({'seed':a.seed,'detergent':t.name,'packing':packing,'protein_atoms':len(protein),'orientation':orientation.__dict__})
 out=Path(a.output); out.mkdir(parents=True,exist_ok=True)
 if issues: report['issues']=issues+report['issues'];report['valid']=False
 if not report['valid']: write_report(report,out/'diagnostics');return 2
 box=box_for(np.vstack([centers,protein]) if len(protein) else centers,a.margin,a.box_shape)
 water=add_solvent(np.vstack([centers,protein]) if len(protein) else centers,box,seed=a.seed,ions=a.ions)
 atoms=[{'name':f'D{i+1}','residue':t.residue,'position':p} for i,p in enumerate(centers)]
 atoms += [{'name':'W','residue':'W','position':p} for p in water]
 write_gro(out/'micelle.gro',atoms,box=box/10)
 (out/'topol.top').write_text(f'; generated by micelle builder\n#include "{t.topology}"\n\n[ system ]\nSpherical detergent micelle\n\n[ molecules ]\n{t.residue:<16} {len(centers)}\nW                 {len(water)}\n')
 report.update({'box_nm':box.tolist(),'water_count':len(water),'ion_count':a.ions,'valid':True})
 if a.mdp: report['grompp']=grompp(out/'topol.top',out/'micelle.gro',a.mdp,out)
 write_report(report,out/'validation');write_manifest(out/'manifest.json',report);return 0
def main(argv=None):
 p=argparse.ArgumentParser(); sub=p.add_subparsers(dest='cmd'); b=sub.add_parser('build'); b.add_argument('--template',required=True);b.add_argument('--protein');b.add_argument('--aggregation-number',type=int,required=True);b.add_argument('--seed',type=int,required=True);b.add_argument('--output',required=True);b.add_argument('--radius',type=float,default=3.);b.add_argument('--margin',type=float,default=2.);b.add_argument('--box-shape',choices=('cubic','rectangular'),default='cubic');b.add_argument('--ions',type=int,default=0);b.add_argument('--mdp')
 v=sub.add_parser('validate');v.add_argument('path'); i=sub.add_parser('inspect');i.add_argument('path'); a=p.parse_args(argv)
 if a.cmd=='build': return build(a)
 if a.cmd in ('validate','inspect'): print(Path(a.path,'validation.json').read_text());return 0
 p.print_help();return 2
if __name__=='__main__':sys.exit(main())
